#!/usr/bin/env python3
"""Generate Markdown documentation beside every YAML file in examples."""

import argparse
import json
import os
from pathlib import Path
import re
import subprocess


ROOT = Path(__file__).resolve().parent
REPOSITORY = ROOT.parent
MARKER = "<!-- Generated by examples/generate_docs.py. -->\n\n"
IMPORT = re.compile(r'''\bimport\s*:\s*(?:'([^']+)'|"([^"]+)"|([^,\s}#]+))''')


def link(path, base):
    return Path(os.path.relpath(path, base)).as_posix()


def code_block(text):
    longest = max((len(run) for run in re.findall(r"`+", text)), default=0)
    fence = "`" * max(3, longest + 1)
    return f"{fence}yaml\n{text.rstrip()}\n{fence}\n"


def references(sources):
    dependencies = {source: set() for source in sources}
    importers = {source: set() for source in sources}
    for source in sources:
        for line in source.read_text(encoding="utf-8").splitlines():
            if line.lstrip().startswith("#"):
                continue
            for match in IMPORT.finditer(line):
                target = (source.parent / next(value for value in match.groups() if value is not None)).resolve()
                if target in importers:
                    dependencies[source].add(target)
                    importers[target].add(source)
    return dependencies, importers


def render(binary, source, importers):
    result = subprocess.run([str(binary), "doc", source.relative_to(REPOSITORY).as_posix()],
                            cwd=REPOSITORY, capture_output=True, text=True, encoding="utf-8")
    events = []
    for line in result.stderr.splitlines():
        try:
            events.append(json.loads(line))
        except json.JSONDecodeError:
            pass
    # A job may remap successful exit code 0 to another value.
    if any(event.get("event") == "finish" and event.get("original_exit_code") == 0 for event in events):
        return "Job", result.stdout
    error = next((event.get("message", "") for event in events if event.get("event") == "error"), "")
    fragment = ("job must be a mapping" in error or "job requires input and output" in error)
    if not fragment or not importers:
        raise RuntimeError(f"{source.relative_to(REPOSITORY)}: {error or result.stderr}")
    text = (f"# Common Definition: {source.name}\n\n"
            "This file is a reusable definition included with `import`. "
            "See the referring job documentation for the expanded fields and settings.\n\n"
            "## Definition\n\n" + code_block(source.read_text(encoding="utf-8")))
    return "Fragment", text


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--dxt", type=Path, default=REPOSITORY / "target/debug/dxt", help="Path to the dxt binary")
    parser.add_argument("--check", action="store_true", help="Check generated documents without modifying files")
    args = parser.parse_args()
    binary = args.dxt.resolve()
    sources = sorted(set(ROOT.rglob("*.yml")) | set(ROOT.rglob("*.yaml")))
    if not sources:
        parser.exit(1, "YAML files not found\n")
    dependencies, importers = references(sources)
    generated = {}
    counts = {"Job": 0, "Fragment": 0}
    index = ["# Example YAML Documentation\n\n",
             "Each YAML file has a Markdown document with the same name in the same directory.\n\n",
             "| YAML | Kind | Documentation |\n| --- | --- | --- |\n"]
    for source in sources:
        kind, markdown = render(binary, source, importers[source])
        destination = source.with_suffix(".md")
        if destination in generated:
            parser.exit(1, f"document filename collision: {destination}\n")
        document = MARKER + f"[Source YAML]({source.name})\n\n" + markdown
        for heading, related in [("Dependencies", dependencies[source]), ("Used by", importers[source])]:
            if related:
                document += f"\n## {heading}\n\n"
                for other in sorted(related):
                    document += f"- [{link(other, source.parent)}]({link(other.with_suffix('.md'), source.parent)})\n"
        generated[destination] = document
        counts[kind] += 1
        relative = source.relative_to(ROOT).as_posix()
        index.append(f"| [{relative}]({relative}) | {kind} | [{destination.name}]({destination.relative_to(ROOT).as_posix()}) |\n")
    generated[ROOT / "DOCUMENTS.md"] = MARKER + "".join(index)
    mismatches = []
    for destination, document in generated.items():
        current = destination.read_text(encoding="utf-8") if destination.exists() else None
        if args.check:
            if current != document:
                mismatches.append(str(destination.relative_to(REPOSITORY)))
        else:
            if current is not None and not current.startswith(MARKER):
                parser.exit(1, f"refusing to overwrite a handwritten document: {destination}\n")
            destination.write_text(document, encoding="utf-8")
    if mismatches:
        parser.exit(1, "document mismatch:\n" + "\n".join(mismatches) + "\n")
    print(f"{'Verified' if args.check else 'Generated'} {len(sources)} YAML documents "
          f"({counts['Job']} jobs, {counts['Fragment']} fragments) and DOCUMENTS.md")


if __name__ == "__main__":
    main()
